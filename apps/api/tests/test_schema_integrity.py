"""Database integrity: constraints reject bad data even if application code has a bug."""
import uuid

import pytest
from sqlalchemy import text
from sqlalchemy.exc import IntegrityError

pytestmark = pytest.mark.usefixtures("seeded")


@pytest.fixture
def db():
    from app.db import SessionLocal

    with SessionLocal() as s:
        yield s
        s.rollback()


def _perfume_id(db):
    return db.execute(text("SELECT id FROM perfumes LIMIT 1")).scalar_one()


@pytest.mark.parametrize("sql", [
    "UPDATE perfumes SET release_year = 1500",
    "UPDATE perfumes SET gender_positioning = 'other'",
    "UPDATE brands SET country = 'gb'",
    "UPDATE perfume_variants SET volume_ml = 0",
    "UPDATE perfume_variants SET gtin = 'ABC123456'",
    "UPDATE perfume_accords SET strength = 101",
    "UPDATE data_sources SET access_method = 'scraped'",
])
def test_check_constraints(db, sql):
    with pytest.raises(IntegrityError):
        db.execute(text(sql))
        db.flush()


def test_alias_cannot_point_at_two_notes(db):
    note_id = db.execute(text("SELECT id FROM notes WHERE slug = 'rose'")).scalar_one()
    with pytest.raises(IntegrityError):
        db.execute(text("INSERT INTO note_aliases (id, note_id, alias, alias_slug) VALUES (:i, :n, 'Orris', 'orris')"),
                   {"i": uuid.uuid4(), "n": note_id})
        db.flush()


def test_brand_with_perfumes_cannot_be_deleted(db):
    with pytest.raises(IntegrityError):
        db.execute(text("DELETE FROM brands WHERE slug = 'casa-ficta'"))
        db.flush()


def test_deleting_a_perfume_cascades_to_its_links(db):
    pid = _perfume_id(db)
    db.execute(text("DELETE FROM perfumes WHERE id = :p"), {"p": pid})
    for table in ("perfume_notes", "perfume_accords", "perfume_variants", "perfume_perfumers"):
        assert db.execute(text(f"SELECT count(*) FROM {table} WHERE perfume_id = :p"), {"p": pid}).scalar() == 0  # noqa: S608


def test_migrations_match_models():
    """Fails if a model changed without a migration (same check CI runs with `alembic check`)."""
    from alembic import command
    from alembic.util.exc import AutogenerateDiffsDetected

    from tests.conftest import alembic_cfg

    try:
        command.check(alembic_cfg())
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        pytest.fail(f"Model/migration drift: {exc}")


def test_seed_refuses_production(monkeypatch, capsys):
    from app.core.config import get_settings
    from app.seed import __main__ as seed_cli

    monkeypatch.setenv("ENVIRONMENT", "production")
    get_settings.cache_clear()
    monkeypatch.setattr("sys.argv", ["seed"])
    try:
        assert seed_cli.main() == 2
        assert "Refusing" in capsys.readouterr().out
    finally:
        monkeypatch.delenv("ENVIRONMENT")
        monkeypatch.setenv("ENVIRONMENT", "ci")
        get_settings.cache_clear()
